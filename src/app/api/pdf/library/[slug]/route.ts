import { NextResponse } from "next/server";
import { eq, sql } from "drizzle-orm";
import { db } from "@/db";
import { pdfResources } from "@/db/schema";
import { getPdfResource } from "@/lib/data";
import { buildContentPdf, siteUrl } from "@/lib/pdf";
import { formatDate, humanFileSize } from "@/lib/format";

export const dynamic = "force-dynamic";

export async function GET(request: Request, context: { params: Promise<{ slug: string }> }) {
  const { slug } = await context.params;
  const resource = await getPdfResource(slug);
  if (!resource) {
    return NextResponse.json({ ok: false, error: "File not found" }, { status: 404 });
  }
  const download = new URL(request.url).searchParams.get("download") === "1";
  if (download) {
    await db
      .update(pdfResources)
      .set({ downloads: sql`${pdfResources.downloads} + 1` })
      .where(eq(pdfResources.id, resource.id));
  }

  const bytes = await buildContentPdf({
    title: resource.titleEn,
    subtitle: `${resource.titleUr} — ${resource.summaryEn}`,
    meta: `${resource.category} · ${resource.speaker ?? "Darul Ifta"} · ${formatDate(resource.resourceDate)} · ${resource.language} · ${resource.pages} pages · ${humanFileSize(resource.fileSizeKb)}`,
    sections: [
      {
        heading: "Summary",
        lines: [resource.summaryEn, resource.summaryUr],
      },
      {
        heading: "Contents",
        lines: [
          "1. Introduction and the importance of the topic.",
          "2. Evidence from the Quran and Sunnah with references.",
          "3. Rulings according to the Hanafi school, with the reasoning of the jurists.",
          "4. Contemporary questions and practical guidance.",
          "5. Summary, du'a and recommended reading.",
        ],
      },
      {
        heading: "A note on this file",
        lines: [
          "This is a sample PDF generated by the server for the demo. In production the original uploaded file is served from private storage, so replacing the file never changes the public link. Scheduled publishing and draft states are held in the admin library.",
          "اردو مواد اصل فائل میں دستیاب ہے۔ نمونہ پی ڈی ایف سرور پر تیار کی گئی ہے۔",
        ],
      },
    ],
    qrUrl: siteUrl(`/library/${resource.slug}`),
  });

  return new NextResponse(Buffer.from(bytes) as unknown as BodyInit, {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `${download ? "attachment" : "inline"}; filename="${resource.slug}.pdf"`,
      "Cache-Control": "public, max-age=600",
    },
  });
}
